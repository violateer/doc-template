-- PostgreSQL 12+ schema. Apply through your database migration process.
-- 与 db/schema.sql（MySQL / MariaDB）保持列一致：加字段时两份都要改，测试会比对列名集合。
CREATE TABLE IF NOT EXISTS doc_template (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_code VARCHAR(100) NOT NULL UNIQUE,
 template_name VARCHAR(200) NOT NULL, file_type VARCHAR(20) NOT NULL, export_type VARCHAR(20) NOT NULL DEFAULT 'ORIGINAL',
 current_version_id BIGINT NULL, status VARCHAR(20) NOT NULL DEFAULT 'ENABLED', remark VARCHAR(500),
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS doc_template_version (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_id BIGINT NOT NULL, version_no INT NOT NULL,
 file_name VARCHAR(255) NOT NULL, file_url VARCHAR(1000) NOT NULL, file_sha256 VARCHAR(64),
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(template_id, version_no)
);
CREATE TABLE IF NOT EXISTS doc_template_data_block (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_id BIGINT NOT NULL, block_code VARCHAR(100) NOT NULL,
 block_name VARCHAR(200) NOT NULL, data_source_type VARCHAR(30) NOT NULL, data_source_config TEXT NOT NULL,
 param_config TEXT, sort_order INT NOT NULL DEFAULT 0, status VARCHAR(20) NOT NULL DEFAULT 'ENABLED',
 UNIQUE(template_id, block_code)
);
CREATE TABLE IF NOT EXISTS doc_template_generate_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_id BIGINT NOT NULL, template_version_id BIGINT NULL,
 export_type VARCHAR(20) NOT NULL, request_params TEXT, result_file_url VARCHAR(1000), status VARCHAR(20) NOT NULL,
 error_message TEXT, create_by VARCHAR(100), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
-- 数据字典：主表一本字典一行（编码 + 名称），子表一行一个「值 → 显示名」。
-- 字典按 dict_code 被转换器引用，dict_code 全局唯一。
CREATE TABLE IF NOT EXISTS doc_template_dict (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dict_code VARCHAR(100) NOT NULL UNIQUE,
 dict_name VARCHAR(200) NOT NULL, remark VARCHAR(500) NULL, create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS doc_template_dict_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dict_id BIGINT NOT NULL, item_value VARCHAR(200) NOT NULL,
 item_label VARCHAR(500) NOT NULL, sort_order INT NOT NULL DEFAULT 0, create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(dict_id, item_value)
);
-- 唯一约束与普通索引在 PostgreSQL 里必须独立建（MySQL 那份写在 CREATE TABLE 里）
CREATE INDEX IF NOT EXISTS idx_dict_item_dict ON doc_template_dict_item (dict_id);
