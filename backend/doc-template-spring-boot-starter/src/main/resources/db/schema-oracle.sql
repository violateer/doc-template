-- Oracle 12c+ 建表脚本。交给宿主的数据库迁移流程执行，或让 Starter 启动时自动建表。
-- 与 db 目录下的 schema.sql（MySQL、MariaDB）、schema-postgresql.sql、schema-sqlserver.sql 保持列一致：
-- 加字段时四份都要改，测试会比对列名集合。
-- 与另外三份的差异：
--   1. Oracle 没有 CREATE TABLE IF NOT EXISTS，幂等靠 PL/SQL 的 EXECUTE IMMEDIATE 加忽略 ORA-00955
--      （名字已被占用）；PL/SQL 块内部自带分号，所以本脚本的语句分隔符是斜杠，不是分号；
--   2. 文本列一律 VARCHAR2(n CHAR) 按字符计长：默认按字节算，中文会提前撞上限；
--   3. 大文本用 CLOB。error_message 例外——它要参与关键字过滤，而 CLOB 不能 LIKE，
--      所以是 VARCHAR2(2000 CHAR)；
--   4. 唯一约束与普通索引分开建（MySQL 那份写在 CREATE TABLE 里）。
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE doc_template (
   id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   template_code VARCHAR2(100 CHAR) NOT NULL UNIQUE,
   template_name VARCHAR2(200 CHAR) NOT NULL,
   file_type VARCHAR2(20 CHAR) NOT NULL,
   export_type VARCHAR2(20 CHAR) DEFAULT ''ORIGINAL'' NOT NULL,
   current_version_id NUMBER(19) NULL,
   status VARCHAR2(20 CHAR) DEFAULT ''ENABLED'' NOT NULL,
   remark VARCHAR2(500 CHAR),
   create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
  )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE <> -955 THEN RAISE; END IF;
END;
