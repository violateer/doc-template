-- AI 导入任务：上传只产生一条任务，分析在后台线程里跑，模板、版本、数据块统一在 APPLY 阶段创建。
-- status：PENDING / RUNNING / SUCCEEDED / FAILED / CANCELED
-- stage：SNAPSHOT / PROMPT / CALL / PARSE / VALIDATE / CHECK / APPLY / DONE
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE doc_template_ai_import (
   id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   file_name VARCHAR2(255 CHAR) NOT NULL,
   file_url VARCHAR2(1000 CHAR) NOT NULL,
   file_sha256 VARCHAR2(64 CHAR),
   file_type VARCHAR2(20 CHAR) NOT NULL,
   template_name VARCHAR2(200 CHAR) NOT NULL,
   template_code VARCHAR2(100 CHAR) NOT NULL,
   hint VARCHAR2(1000 CHAR),
   status VARCHAR2(20 CHAR) DEFAULT ''PENDING'' NOT NULL,
   stage VARCHAR2(20 CHAR),
   template_id NUMBER(19) NULL,
   plan_json CLOB,
   error_message VARCHAR2(2000 CHAR),
   create_by VARCHAR2(100 CHAR),
   create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   start_time TIMESTAMP NULL,
   finish_time TIMESTAMP NULL,
   elapsed_ms NUMBER(19)
  )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE <> -955 THEN RAISE; END IF;
END;
/
