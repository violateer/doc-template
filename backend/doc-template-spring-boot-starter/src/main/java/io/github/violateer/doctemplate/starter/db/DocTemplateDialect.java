package io.github.violateer.doctemplate.starter.db;

import org.springframework.jdbc.core.namedparam.MapSqlParameterSource;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.support.KeyHolder;

import java.util.Locale;
import java.util.Optional;

/**
 * 数据库方言：把「各家 SQL 写法不一样」的三处收在一个枚举里。
 *
 * <p>整个持久层是手写 SQL + Spring JDBC，没有 ORM，所以方言差异只落在三个点上：
 * 建表脚本用哪份、分页怎么写、插入后怎么取回自增主键。其余 SQL（命名参数、列名不加引号）
 * 本来就是跨库的。</p>
 *
 * <p><b>内部实现，不属于对外契约</b>：宿主不需要引用这个类，也不该按它写扩展。</p>
 */
public enum DocTemplateDialect {

    /** MySQL 8 / MariaDB：{@code AUTO_INCREMENT} + {@code LIMIT n OFFSET m}。 */
    MYSQL("MySQL / MariaDB", "db/schema.sql"),

    /** PostgreSQL 12+：{@code GENERATED BY DEFAULT AS IDENTITY}，分页写法与 MySQL 相同。 */
    POSTGRESQL("PostgreSQL", "db/schema-postgresql.sql");

    private final String displayName;
    private final String schemaScript;

    DocTemplateDialect(String displayName, String schemaScript) {
        this.displayName = displayName;
        this.schemaScript = schemaScript;
    }

    /** 建表脚本在 classpath 上的位置。 */
    public String schemaScript() {
        return schemaScript;
    }

    /** 用于日志与错误提示的数据库名。 */
    public String displayName() {
        return displayName;
    }

    /**
     * 给一条已带 {@code ORDER BY} 的查询套上分页。
     *
     * <p>{@code offset} / {@code limit} 是模块内部的 {@code int}，直接拼进 SQL 文本而不是走占位符：
     * 部分方言的 {@code FETCH NEXT} 只接受字面量，统一拼文本才能让四种方言共用同一个签名，
     * 也就不存在注入问题。</p>
     */
    public String page(String sql, int offset, int limit) {
        return switch (this) {
            case MYSQL, POSTGRESQL -> sql + " LIMIT " + limit + " OFFSET " + offset;
        };
    }

    /**
     * 插入并回填自增主键。
     *
     * <p>MySQL / PostgreSQL 都能用 {@link java.sql.Statement#RETURN_GENERATED_KEYS} 直接取回；
     * 需要按列名取键的库（例如 Oracle）在这一处分支即可，调用方不用改。</p>
     */
    public void insert(NamedParameterJdbcTemplate jdbc, String sql, MapSqlParameterSource params, KeyHolder keys) {
        jdbc.update(sql, params, keys);
    }

    /**
     * 按 JDBC 的 {@code DatabaseMetaData.getDatabaseProductName()} 识别方言。
     *
     * <p>返回 {@link Optional#empty()} 表示不认识 —— 由调用方决定是报错还是忽略：
     * 自动建表时要报错，日常查询时没必要。</p>
     */
    public static Optional<DocTemplateDialect> fromProductName(String productName) {
        String name = productName == null ? "" : productName.toLowerCase(Locale.ROOT);
        if (name.contains("mysql") || name.contains("mariadb")) return Optional.of(MYSQL);
        if (name.contains("postgresql")) return Optional.of(POSTGRESQL);
        return Optional.empty();
    }

    /** 当前支持的数据库名，拼错误提示用。 */
    public static String supported() {
        StringBuilder text = new StringBuilder();
        for (DocTemplateDialect dialect : values()) {
            if (text.length() > 0) text.append(" / ");
            text.append(dialect.displayName);
        }
        return text.toString();
    }
}
